//! Path-based classification of a discovered file as `authored`, `generated`,
//! or `vendored`.
//!
//! This exists because a mechanic's rows are often dominated by files nobody
//! in the project wrote — 49,800 of 50,000 call sites under `vendor/` is one
//! sentence, not a list — and a caller can only say that sentence if the fact
//! is on the row. `report.completeness.file_class_counts` and any
//! `GROUP BY files.file_class` over `leads`/`query` results then collapse the
//! noise without a verdict: a count of vendored rows is a fact about where the
//! code came from, never about whether it matters.
//!
//! The classification is derived from the **path alone** — never from file
//! content — so it is free to compute at write time and is available for
//! skipped (never-read) rows too. It is a heuristic, and the schema's
//! `file_class` comment says so: a hand-written file whose *name* tokenizes
//! to `generated` is classified `generated`, and a directory named `vendor`
//! is `vendored` even if its contents were written by hand. `vendored` wins
//! when a path matches both, because "third party" is the more specific
//! explanation of why a file is not the project's own.
//!
//! `files.file_class` is the SQL mirror of [`classify`]; a variant added to
//! [`FileClass`] must be added to the schema's CHECK in the same change.

/// `files.file_class`. Mirrored in `src/store/schema.sql`'s
/// `CHECK (file_class IN (...))`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum FileClass {
    Authored,
    Generated,
    Vendored,
}

impl FileClass {
    /// The stable text tag stored in `files.file_class`.
    #[must_use]
    pub(super) fn as_sql_text(self) -> &'static str {
        match self {
            Self::Authored => "authored",
            Self::Generated => "generated",
            Self::Vendored => "vendored",
        }
    }
}

/// Directory names that mark a third-party dependency tree. Matched on a
/// whole, ASCII-lowercased path segment and only in a directory position, so
/// a file named `vendor.rs` is not vendored but everything under `vendor/`
/// is. `pods` is CocoaPods' checkout directory (`Pods/` at the project
/// root); `site-packages`/`dist-packages` are Python's installed-dependency
/// trees; `venv`/`.venv`/`virtualenv` are Python virtual environments.
const VENDORED_SEGMENTS: &[&str] = &[
    "vendor",
    "vendors",
    "third_party",
    "third-party",
    "thirdparty",
    "node_modules",
    "bower_components",
    "jspm_packages",
    "site-packages",
    "dist-packages",
    "pods",
    "venv",
    ".venv",
    "virtualenv",
];

/// Filename suffixes that only a generator emits. The rest of the generated
/// signal is the `generated` path token, which covers the many codegen tools
/// that name their output `*_generated.*` or write into a `generated/`
/// directory.
const GENERATED_SUFFIXES: &[&str] = &[
    ".min.js",
    ".min.mjs",
    ".min.css",
    ".pb.go",
    ".pb.cc",
    ".pb.cpp",
    ".pb.c",
    ".pb.h",
    ".pb.hh",
    ".pb.java",
    ".pb.swift",
    "_pb2.py",
    "_pb2.pyi",
    "_pb2_grpc.py",
    ".g.cs",
    ".designer.cs",
    ".g.dart",
    ".freezed.dart",
    ".gen.go",
    ".gen.ts",
];

/// True when any alphanumeric run in `segment` is the word `generated` or
/// `autogenerated` — so `src/generated/api.rs`, `zz_generated.deepcopy.go`,
/// and `foo_autogenerated.rs` match while `regenerated.rs` does not.
fn names_generated_code(segment: &str) -> bool {
    segment
        .split(|character: char| !character.is_ascii_alphanumeric())
        .any(|token| token == "generated" || token == "autogenerated")
}

/// Classifies a project-relative path. See the module docs for the rule and
/// its documented heuristic limits.
#[must_use]
pub(super) fn classify(relative_path: &str) -> FileClass {
    let lower = relative_path.to_ascii_lowercase();
    let mut segments: Vec<&str> = lower.split(['/', '\\']).collect();
    let file_name = segments.pop().unwrap_or("");
    let is_vendored = segments
        .iter()
        .any(|segment| VENDORED_SEGMENTS.contains(segment));
    if is_vendored {
        return FileClass::Vendored;
    }
    let generated_segment = file_name_or_dirs_are_generated(&segments, file_name);
    if generated_segment
        || GENERATED_SUFFIXES
            .iter()
            .any(|suffix| file_name.ends_with(suffix))
    {
        return FileClass::Generated;
    }
    FileClass::Authored
}

/// A `generated` token anywhere in the path — the file name or any directory.
fn file_name_or_dirs_are_generated(dirs: &[&str], file_name: &str) -> bool {
    names_generated_code(file_name) || dirs.iter().any(|dir| names_generated_code(dir))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_ordinary_source_path_is_authored() {
        assert_eq!(classify("src/auth/login.rs"), FileClass::Authored);
        assert_eq!(classify("README.md"), FileClass::Authored);
        assert_eq!(classify("src/vendor.rs"), FileClass::Authored);
    }

    #[test]
    fn a_third_party_directory_is_vendored() {
        assert_eq!(classify("vendor/foo/bar.go"), FileClass::Vendored);
        assert_eq!(
            classify("node_modules/left-pad/index.js"),
            FileClass::Vendored
        );
        assert_eq!(
            classify("Pods/Alamofire/Source/Alamofire.swift"),
            FileClass::Vendored
        );
        assert_eq!(
            classify("site-packages/django/db/models.py"),
            FileClass::Vendored
        );
    }

    #[test]
    fn a_generated_path_or_suffix_is_generated() {
        assert_eq!(classify("src/generated/api.rs"), FileClass::Generated);
        assert_eq!(classify("api/service.pb.go"), FileClass::Generated);
        assert_eq!(classify("web/app.min.js"), FileClass::Generated);
        assert_eq!(classify("zz_generated.deepcopy.go"), FileClass::Generated);
        assert_eq!(classify("models/user_pb2.py"), FileClass::Generated);
        assert_eq!(classify("ui/widget.freezed.dart"), FileClass::Generated);
    }

    #[test]
    fn a_generated_file_inside_a_vendored_tree_is_vendored() {
        assert_eq!(classify("vendor/mod.pb.go"), FileClass::Vendored);
        assert_eq!(
            classify("node_modules/x/generated/api.rs"),
            FileClass::Vendored
        );
    }

    #[test]
    fn a_word_containing_generated_is_not_generated() {
        assert_eq!(classify("src/regenerated.rs"), FileClass::Authored);
        assert_eq!(classify("src/ungenerated_notes.md"), FileClass::Authored);
    }

    #[test]
    fn the_sql_text_is_the_stable_stored_tag() {
        assert_eq!(FileClass::Authored.as_sql_text(), "authored");
        assert_eq!(FileClass::Generated.as_sql_text(), "generated");
        assert_eq!(FileClass::Vendored.as_sql_text(), "vendored");
    }
}
